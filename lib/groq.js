// =============================================================================
// lib/groq.js
// -----------------------------------------------------------------------------
// Two jobs, both going through the same low-level callGroq():
//
//   1. phraseFacts(factsBlock)
//        Same philosophy as before: turn an already-resolved, locally-built
//        factsBlock into one natural sentence. Groq cannot add numbers that
//        aren't in factsBlock because factsBlock is the ONLY thing it's shown.
//
//   2. routeConversation(history, userMessage, groundTruth)
//        NEW. Used only when local resolveIntent() found no direct match
//        (no condition name, no FAQ keyword, no discovery keyword). Groq is
//        given the real conversation history plus a fixed "ground truth"
//        block about what Verity is, and one of two things happens:
//
//          a) It answers directly in plain text (greetings, "who are you",
//             "is verity a research platform", "oh damn" after a fact was
//             just shown, typos like "whatsup", short replies like "sure"/
//             "yes"/"no" that only make sense next to the previous turn).
//
//          b) It decides the user wants specific numeric data it doesn't
//             have, and replies with ONLY a JSON action object, e.g.
//             {"action":"lookup_condition","slug":"autism"} or
//             {"action":"discovery"}. No numbers are ever produced by Groq
//             in this path — the action just tells api/chat.js what to look
//             up locally, and a second phraseFacts() call (or the
//             deterministic template) produces the real answer.
//
// This keeps the non-negotiable: every specific statistic the user sees was
// read out of conditions.js, never generated by the model.
// =============================================================================

const GROQ_API_URL = 'https://api.groq.com/openai/v1/chat/completions';
const GROQ_MODEL = process.env.GROQ_MODEL || 'openai/gpt-oss-120b';

async function callGroq(messages, { maxTokens = 220, temperature = 0.6 } = {}) {
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) {
    console.error('GROQ_API_KEY is not set.');
    return null;
  }

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 8000);

  try {
    const res = await fetch(GROQ_API_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model: GROQ_MODEL,
        messages,
        max_tokens: maxTokens,
        temperature,
      }),
      signal: controller.signal,
    });

    if (!res.ok) {
      console.error('Groq API error:', res.status, await res.text());
      return null;
    }

    const data = await res.json();
    const text = data?.choices?.[0]?.message?.content;
    return typeof text === 'string' ? text.trim() : null;
  } catch (err) {
    console.error('Groq request failed:', err.message);
    return null;
  } finally {
    clearTimeout(timeout);
  }
}

// -----------------------------------------------------------------------
// 1. Fact phrasing (used whenever resolveIntent() already found a factsBlock)
// -----------------------------------------------------------------------
export async function phraseFacts(factsBlock) {
  const messages = [
    {
      role: 'system',
      content:
        'You are Verity\u2019s assistant. Rewrite the facts below into one warm, ' +
        'natural, conversational reply (1\u20133 sentences). Use ONLY the facts ' +
        'given \u2014 never invent, estimate, or add a number, condition, or ' +
        'source that is not explicitly present below. Do not include links or ' +
        'URLs, those are added separately.',
    },
    { role: 'user', content: factsBlock },
  ];

  return callGroq(messages, { maxTokens: 160, temperature: 0.5 });
}

// -----------------------------------------------------------------------
// 2. Conversational router (used when nothing matched locally)
// -----------------------------------------------------------------------
export async function routeConversation({ history, userMessage, groundTruth, conditionList }) {
  const systemPrompt = `You are the conversational assistant for Verity, a live research-transparency platform. Talk like a helpful, friendly assistant (think an early ChatGPT) \u2014 warm, brief, natural. Understand typos, slang, and short replies ("sure", "yes", "no", "whatsup") by reading the conversation history; never treat a short reply in isolation.

GROUND TRUTH about Verity (you may state these facts freely, they are fixed and always true):
${groundTruth}

CONDITIONS AVAILABLE ON VERITY (names only \u2014 you do NOT know their scores):
${conditionList}

OUTPUT FORMAT \u2014 this is strict, follow it exactly every single time:
Respond with ONE JSON object and absolutely nothing else. No sentence before it, no sentence after it, no explanation of the JSON. Never combine a reply and a JSON action in the same message. Use exactly one of these three shapes:

  {"type":"say","text":"<your natural 1-2 sentence reply>"}
  {"type":"lookup_condition","slug":"<slug-from-the-list-above>"}
  {"type":"discovery"}

RULES:
- Use "say" for: identity/small-talk/"what is Verity"/greetings/acknowledgments/clarifying questions \u2014 anything that isn't a request for a specific number.
- You must NEVER state or estimate a specific representation score, number, or statistic inside "text" \u2014 you don't have that data. If the user wants data, use "lookup_condition" or "discovery" instead of "say", and DO NOT also write a sentence about it \u2014 the number will be phrased and shown separately after your action runs.
- Use "lookup_condition" only when the message and history clearly point to one specific condition from the list.
- Use "discovery" when the user wants something random, or agrees to be surprised after it was offered.
- If it's genuinely unclear which condition they mean, use "say" and ask a short, friendly clarifying question \u2014 do not guess a slug.
- Never use the phrase "I'm not sure what you meant" \u2014 always engage with what they likely meant instead.

Example: user says "hi" \u2192 {"type":"say","text":"Hi! What would you like to know?"}
Example: user says "tell me about ADHD" \u2192 {"type":"lookup_condition","slug":"adhd"}
Example: user says "surprise me" \u2192 {"type":"discovery"}
Example: user says "good" (after you just showed a fact) \u2192 {"type":"say","text":"Glad you liked it! Want me to surprise you with another one?"}`;

  const messages = [
    { role: 'system', content: systemPrompt },
    ...history.map((t) => ({ role: t.role, content: t.content })),
    { role: 'user', content: userMessage },
  ];

  return callGroq(messages, { maxTokens: 200, temperature: 0.5 });
}

// -----------------------------------------------------------------------
// Repair retry: used only when routeConversation()'s reply didn't contain
// valid JSON (rare, but happens on complex/reflective questions that tempt
// the model into free prose). Sends the same context back with a blunt
// correction instead of immediately giving up to the generic fallback.
// -----------------------------------------------------------------------
export async function repairRouterFormat({ history, userMessage, groundTruth, conditionList, badReply }) {
  const messages = [
    {
      role: 'system',
      content: `You are Verity's assistant. Your last reply broke the required output format. You MUST respond with exactly one JSON object and nothing else, in one of these shapes:
  {"type":"say","text":"<your natural 1-2 sentence reply>"}
  {"type":"lookup_condition","slug":"<slug>"}
  {"type":"discovery"}
No text before or after the JSON. Ground truth you may draw on for "text":
${groundTruth}
Conditions: ${conditionList}`,
    },
    ...history.map((t) => ({ role: t.role, content: t.content })),
    { role: 'user', content: userMessage },
    { role: 'assistant', content: badReply },
    { role: 'user', content: 'That was not valid JSON. Resend your answer as exactly one JSON object in the required format, nothing else.' },
  ];

  return callGroq(messages, { maxTokens: 200, temperature: 0.3 });
}